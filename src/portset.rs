/// Single input port wrapper. Use when a Machine has exactly one input port.
///
/// ```ignore
/// impl Machine for Doubler {
///     type Input = In<i32>;
///     type Output = Out<i32>;
///     type Ports = SinglePorts<i32>;
///     // ...
/// }
/// ```
///
/// `Debug`/`Clone`/`PartialEq` are **conditional** on `T` (hand-written impls,
/// not derives) — axiom does not force `T: Clone`, matching the Clone-free
/// `HasPortInfo` contract.
pub struct In<T>(pub T);

impl<T: core::fmt::Debug> core::fmt::Debug for In<T> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_tuple("In").field(&self.0).finish()
    }
}

impl<T: Clone> Clone for In<T> {
    fn clone(&self) -> Self {
        In(self.0.clone())
    }
}

impl<T: PartialEq> PartialEq for In<T> {
    fn eq(&self, other: &Self) -> bool {
        self.0 == other.0
    }
}

impl<T: Send + 'static> HasPortInfo for In<T> {
    fn port_name(&self) -> &'static str { "input" }
    fn flow_kind(&self) -> FlowKind { FlowKind::Data }
    fn payload_type_id(&self) -> TypeId { TypeId::of::<T>() }
    fn payload_type_name(&self) -> &'static str { core::any::type_name::<T>() }
    fn from_port_name(name: &str, payload: Box<dyn Any + Send>) -> Option<Self> {
        match name {
            "input" => payload.downcast::<T>().ok().map(|v| In(*v)),
            _ => None,
        }
    }
    fn into_any(self) -> Box<dyn Any + Send> { Box::new(self.0) }
}

impl<T: Send + 'static> Pack for In<T> {
    type Raw = T;
    fn pack(raw: T) -> Self {
        In(raw)
    }
}

/// Single output port wrapper. Use when a Machine has exactly one output port.
///
/// `Debug`/`Clone`/`PartialEq` are **conditional** on `T` — see [`In`].
pub struct Out<T>(pub T);

impl<T: core::fmt::Debug> core::fmt::Debug for Out<T> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_tuple("Out").field(&self.0).finish()
    }
}

impl<T: Clone> Clone for Out<T> {
    fn clone(&self) -> Self {
        Out(self.0.clone())
    }
}

impl<T: PartialEq> PartialEq for Out<T> {
    fn eq(&self, other: &Self) -> bool {
        self.0 == other.0
    }
}

impl<T: Send + Sync + 'static> HasPortInfo for Out<T> {
    fn port_name(&self) -> &'static str { "output" }
    fn flow_kind(&self) -> FlowKind { FlowKind::Data }
    fn payload_type_id(&self) -> TypeId { TypeId::of::<T>() }
    fn payload_type_name(&self) -> &'static str { core::any::type_name::<T>() }
    fn from_port_name(name: &str, payload: Box<dyn Any + Send>) -> Option<Self> {
        match name {
            "output" => payload.downcast::<T>().ok().map(|v| Out(*v)),
            _ => None,
        }
    }
    fn into_any(self) -> Box<dyn Any + Send> { Box::new(self.0) }
}

impl<T: Send + 'static> Unpack for Out<T> {
    type Raw = T;
    fn unpack(self) -> T {
        self.0
    }
}

/// PortSet for a single-input, single-output Machine (both Data flow).
///
/// Use with `In<T>` and `Out<T>`.
pub struct SinglePorts<T>(core::marker::PhantomData<T>);

impl<T: Send + Sync + 'static> PortSet for SinglePorts<T> {
    type Input = In<T>;
    type Output = Out<T>;

    fn port_schema() -> PortSchema {
        PortSchema::new()
            .with(crate::port::PortDecl::input::<T>("input"))
            .with(crate::port::PortDecl::output::<T>("output"))
    }
}

